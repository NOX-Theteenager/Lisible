export const applyFont = (t, font) => (font && FONTS[font] ? { ...t, font: FONTS[font], fontName: font } : t);
export function resolveTpl(key, acc) {
  const d = TPLS[key] || TPLS.classique,
    r = (x) => (typeof x === 'string' ? x.replace('ACC', acc) : x);
  const o = {};
  Object.keys(d).forEach((k) => (o[k] = r(d[k])));
  const b = ATSB[d.ats];
  return {
    ...o,
    key,
    accent: acc,
    tint: acc + '1f',
    titleColor: o.titleC || acc,
    headColor: o.headC,
    isText: d.header === 'text',
    isBand: d.header === 'band',
    isSig: d.header === 'sig',
    twoCol: !!d.twoCol,
    cols: d.twoCol ? '34% 1fr' : '1fr',
    bodyPad: d.twoCol ? '34px 32px 44px' : d.header === 'text' ? '0 50px 48px' : '10px 44px 48px',
    dateTop: !d.dateLeft,
    isDesign: d.fam === 'design',
    atsLabel: b[0],
    atsBg: b[1],
    atsFg: b[2],
  };
}
